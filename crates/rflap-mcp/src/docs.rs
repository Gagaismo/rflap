//! `docs/mcp-tools.md`, generated from the same catalogue `tools/list` serves, so the reference
//! cannot drift (a test compares the file with this output).

use std::fmt::Write;

use serde_json::Value;

use crate::schemas::{self, ToolDef};

fn type_of(schema: &Value) -> String {
    if let Some(kind) = schema["type"].as_str() {
        return match (kind, schema["enum"].as_array()) {
            ("string", Some(values)) => values
                .iter()
                .filter_map(Value::as_str)
                .map(|v| format!("`{v}`"))
                .collect::<Vec<_>>()
                .join(r" \| "),
            ("array", _) => format!("array of {}", type_of(&schema["items"])),
            (kind, _) => kind.to_string(),
        };
    }
    match schema["anyOf"].as_array() {
        Some(options) => options.iter().map(type_of).collect::<Vec<_>>().join(" or "),
        None => "any".into(),
    }
}

fn cell(text: &str) -> String {
    text.replace('|', r"\|").replace('\n', " ")
}

fn tool(out: &mut String, def: &ToolDef) {
    let _ = writeln!(out, "## `{}`\n", def.name);
    let _ = writeln!(
        out,
        "**{}**{}\n",
        def.title,
        if def.visual {
            " · shows the widget"
        } else {
            ""
        }
    );
    let _ = writeln!(out, "{}\n", def.description);
    let properties = def.input["properties"]
        .as_object()
        .cloned()
        .unwrap_or_default();
    if properties.is_empty() {
        let _ = writeln!(out, "No arguments.\n");
    } else {
        let required: Vec<&str> = def.input["required"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        let _ = writeln!(
            out,
            "| argument | type | required | description |\n|---|---|---|---|"
        );
        for (name, schema) in &properties {
            let _ = writeln!(
                out,
                "| `{name}` | {} | {} | {} |",
                type_of(schema),
                if required.contains(&name.as_str()) {
                    "yes"
                } else {
                    "no"
                },
                cell(schema["description"].as_str().unwrap_or_default())
            );
        }
        out.push('\n');
    }
    if let Some(keys) = def
        .output
        .as_ref()
        .and_then(|o| o["properties"].as_object())
    {
        let names: Vec<String> = keys.keys().map(|k| format!("`{k}`")).collect();
        let _ = writeln!(out, "`structuredContent` keys: {}.\n", names.join(", "));
    }
}

/// The tool reference as Markdown.
pub fn tools_markdown() -> String {
    let mut out = String::from(
        "# Rflap MCP tools\n\n\
         <!-- Generated by `rflap-mcp --tools-markdown`; a test keeps this file in sync. -->\n\n\
         Every tool answers with `content` (Markdown for chats without the widget) and, when it \
         succeeds, `structuredContent` (the Rflap API result; visual tools add `tool` and, when \
         they have one, `document`). A failure is a result with `isError: true` and the API's \
         error code and message, never a JSON-RPC error. Tools marked *shows the widget* carry \
         `_meta.ui.resourceUri = \"ui://rflap/editor.html\"`.\n\n",
    );
    for def in schemas::tools() {
        tool(&mut out, &def);
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
