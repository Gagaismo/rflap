/** The supported language of the first usable candidate (`es-AR` -> `es`), English if none. */
export function pickLocale(candidates) {
  for (const candidate of candidates || []) {
    if (typeof candidate !== 'string') continue;
    const base = candidate.toLowerCase().split(/[-_]/)[0];
    if (dictionaries[base]) return base;
  }
  return 'en';
}

/** Adds strings: `registerStrings({ en: {'k': 'v'}, es: {...} })`. Existing keys are overwritten. */
export function registerStrings(extra) {
  for (const [locale, entries] of Object.entries(extra)) {
    dictionaries[locale] = Object.assign(dictionaries[locale] || {}, entries);
  }
}

export function createI18n(locale = 'en') {
  const state = { locale: pickLocale([locale]) };
  return {
    get locale() {
      return state.locale;
    },
    setLocale(next) {
      state.locale = pickLocale([next]);
    },
    t(key, params = {}) {
      const text = (dictionaries[state.locale] && dictionaries[state.locale][key]) ?? dictionaries.en[key] ?? key;
      return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
    },
  };
}

/** The app-wide instance. */
export const i18n = createI18n('en');
export const t = (key, params) => i18n.t(key, params);
export const setLanguage = (locale) => i18n.setLocale(locale);
